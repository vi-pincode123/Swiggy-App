export const getDiscount = (product) =>
  Math.round(((product.mrp - product.price) / product.mrp) * 100)

export const getProduct = (id) => GROCERY_PRODUCTS.find((product) => product.id === id)

export const getFilterLabel = (filterId) => FILTER_LABELS[filterId] || 'All groceries'

export function matchesFilter(product, filterId) {
  if (!filterId) return true

  switch (filterId) {
    case 'fresh':
      return product.category === 'fruits-vegetables'
    case 'dairy':
      return product.category === 'dairy-bakery'
    case 'beauty':
      return product.category === 'personal-care'
    case 'electronics':
      return product.category === 'electronics'
    case 'snacks':
      return (
        product.category === 'snacks-munchies' || product.category === 'cold-drinks-juices'
      )
    case 'home-essentials':
      return product.category === 'household-essentials'
    case 'switch':
    case 'diwali':
    case 'kids':
      return product.tags.includes(filterId)
    case 'maxx-savings':
      return getDiscount(product) >= 25
    case 'bestsellers':
      return product.tags.includes('best-seller')
    case 'trending':
      return product.tags.includes('trending')
    default:
      return product.category === filterId
  }
}

export function searchProducts(products, query) {
  const term = query.trim().toLowerCase()
  if (!term) return products

  return products.filter((product) => {
    const haystack = [
      product.name,
      product.quantity,
      CATEGORY_LABELS[product.category] || '',
      ...product.tags,
    ]
      .join(' ')
      .toLowerCase()

    return haystack.includes(term)
  })
}

export function sortProducts(products, sortBy) {
  const list = [...products]

  if (sortBy === 'price-low') return list.sort((a, b) => a.price - b.price)
  if (sortBy === 'price-high') return list.sort((a, b) => b.price - a.price)

  return list.sort((a, b) => b.popularity - a.popularity)
}
